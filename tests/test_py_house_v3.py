def main():
    engine = RuleBasedAddressTaggingEngine()
    passed = 0
    failed = 0
    failed_cases = []

    for addr, expected in USER_SAMPLES:
        r = engine.parse_single(addr)
        actual = r['house']
        if actual == expected:
            passed += 1
        else:
            failed += 1
            failed_cases.append((addr, expected, actual, r))

    total = passed + failed
    print(f'==== 测试结果 ====')
    print(f'总数: {total}, 通过: {passed}, 失败: {failed}')
    print(f'准确率: {passed / total * 100:.2f}%\n')

    if failed_cases:
        print('---- 失败用例 ----')
        for addr, expected, actual, r in failed_cases:
            print(f'地址: {addr}')
            print(f'  期望: "{expected}"')
            print(f'  实际: "{actual}"')
            print(f'  完整: road="{r["road"]}", roadno="{r["roadno"]}", '
                  f'area="{r["area"]}", bldg="{r["bldg"]}", '
                  f'unit="{r["unit"]}", floor="{r["floor"]}", house="{r["house"]}"')
            print()


if __name__ == '__main__':
    main()
