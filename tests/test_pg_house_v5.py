    total_failed = f1 + f2 + f3 + f4
    total = total_passed + total_failed
    print('=' * 70)
    print('汇总')
    print('=' * 70)
    print(f'总通过: {total_passed}/{total}, 总失败: {total_failed}')
    print(f'总准确率: {total_passed / total * 100:.2f}%' if total > 0 else 'N/A')

    if total_failed > 0:
        sys.exit(1)


