def run_test_suite(cur, title, samples):
    """运行一组测试样例，返回 (passed, failed, failed_cases)。"""
    print('=' * 70)
    print(title)
    print('=' * 70)
    passed = 0
    failed = 0
    failed_cases = []

    for addr, expected in samples:
        cur.execute("SELECT extract_house_number(%s)", (addr,))
        actual = cur.fetchone()[0] or ''
        if actual == expected:
            passed += 1
        else:
            failed += 1
            failed_cases.append((addr, expected, actual))

    total = passed + failed
    accuracy = passed / total * 100 if total > 0 else 0
    print(f'总数: {total}, 通过: {passed}, 失败: {failed}')
    print(f'准确率: {accuracy:.2f}%\n')

    if failed_cases:
        print('---- 失败用例 ----')
        for addr, expected, actual in failed_cases:
            print(f'地址: {addr}')
            print(f'  期望: "{expected}"')
            print(f'  实际: "{actual}"')
            print()

    return passed, failed, failed_cases


